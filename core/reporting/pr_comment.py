"""PR Report Markdown generation (Step 24)."""

from core.detection.models import DetectionRule
from core.testing.models import TestResult
from core.validation.report import SchemaCompatibilityReport
from core.versioning.diff import RuleDiff
from core.versioning.pr_parser import ReasonType


def generate_pr_comment(
    rule: DetectionRule,
    schema_report: SchemaCompatibilityReport,
    test_results: list[TestResult],
    rule_diff: RuleDiff,
    reason: ReasonType
) -> str:
    """Generate the GitHub PR comment markdown for a single rule."""
    
    # 1. Header
    md = f"## :shield: DRAVE Report: `{rule.name}`\n\n"
    
    # 2. Summary Table
    tests_passed = sum(1 for r in test_results if r.status == "PASS")
    total_tests = len(test_results)
    
    schema_status = ":white_check_mark: PASS" if schema_report.compatibility_pct == 100 else ":warning: WARN"
    tests_status = ":white_check_mark: PASS" if tests_passed == total_tests and total_tests > 0 else ":x: FAIL"
    
    md += "| Check | Status | Details |\n"
    md += "|-------|--------|---------|\n"
    md += f"| **Schema** | {schema_status} | {schema_report.compatibility_pct}% compatible |\n"
    md += f"| **Tests** | {tests_status} | {tests_passed}/{total_tests} passed |\n"
    md += f"| **Reason** | :information_source: INFO | `{reason}` |\n\n"

    # 3. Schema Details
    if schema_report.error or schema_report.missing_required_fields or schema_report.missing_optional_fields:
        md += "<details><summary><b>Schema Diagnostics</b></summary>\n\n"
        if schema_report.error:
            md += f"- **Error**: {schema_report.error}\n"
        if schema_report.missing_required_fields:
            md += f"- **Missing Required**: `{', '.join(schema_report.missing_required_fields)}`\n"
        if schema_report.missing_optional_fields:
            md += f"- **Missing Optional**: `{', '.join(schema_report.missing_optional_fields)}`\n"
        md += "\n</details>\n\n"

    # 4. Test Details
    if test_results:
        md += "<details><summary><b>Test Results</b></summary>\n\n"
        md += "| Test ID | Status | Diagnostics |\n"
        md += "|---------|--------|-------------|\n"
        for tr in test_results:
            diag = tr.diagnostics.get('error_msg', '')
            status_icon = ":white_check_mark:" if tr.status == "PASS" else ":x:"
            md += f"| `{tr.test_id}` | {status_icon} {tr.status} | {diag} |\n"
        md += "\n</details>\n\n"

    # 5. Diff Details
    md += "<details><summary><b>Rule Diff</b></summary>\n\n"
    md += f"**Author**: {rule_diff.author} | **Commit**: `{rule_diff.commit_head[:7]}`\n\n"
    md += "```diff\n"
    md += rule_diff.diff_text + "\n"
    md += "```\n"
    md += "</details>\n\n"
    
    md += "---\n*Generated by DRAVE Detection Engine*"
    
    return md
